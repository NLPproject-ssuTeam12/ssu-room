def course_alias_hits(norm_text: str, names: List[str], norm) -> Tuple[List[str], str]:
    """줄임말로 과목 찾기 (긴 줄임말 먼저). 지금 데이터에 있는 과목만. -> (후보 과목명, 줄임말을 지운 글)."""
    by_norm = {norm(n): n for n in names}
    for abbr in sorted(COURSE_ALIAS, key=len, reverse=True):
        if abbr in norm_text:
            hits = [by_norm[norm(x)] for x in COURSE_ALIAS[abbr] if norm(x) in by_norm]
            if hits:
                return hits, norm_text.replace(abbr, " ", 1)
    return [], norm_text


def alias_table_text(names: List[str], norm) -> str:
    """언어 모델 프롬프트용: 지금 데이터에 있는 과목의 줄임말만 '줄임말 → 과목명' 줄로."""
    have = {norm(n) for n in names}
    rows = []
    for abbr, targets in COURSE_ALIAS.items():
        got = [t for t in targets if norm(t) in have]
        if got:
            rows.append(f"{abbr} → {' 또는 '.join(got)}")
    return "\n".join(rows) or "(없음)"
